from pathlib import Path
import argparse
import struct
import subprocess

parser = argparse.ArgumentParser()
parser.add_argument("glslang", help="Path to glslangValidator")
parser.add_argument("--output-dir", default="output/framegraph-shaders")
args = parser.parse_args()
source = Path(__file__).parent
lines = ["#pragma once", "#include <cstdint>", "", "// Generated by regenerate.py; edit the GLSL sources.", "// clang-format off"]
directory = Path(args.output_dir).resolve()
directory.mkdir(parents=True, exist_ok=True)
for name, file, defines in [
        ("FrameGraphVS", "FrameGraph.vert", []),
        ("FrameGraphRedFS", "FrameGraph.frag", ["-DRED=1", "-DGREEN=0"]),
        ("FrameGraphGreenFS", "FrameGraph.frag", ["-DRED=0", "-DGREEN=1"]),
        ("FrameGraphIndexedVS", "FrameGraphIndexed.vert", []),
        ("FrameGraphIndexedFS", "FrameGraphIndexed.frag", ["-DMATERIAL_BINDING=0"]),
        ("FrameGraphIndexedAlternateFS", "FrameGraphIndexed.frag", ["-DMATERIAL_BINDING=1"]),
]:
    binary = directory / (name + ".spv")
    subprocess.run([args.glslang, "-V", "--target-env", "vulkan1.3", *defines, "-o", str(binary), str(source / file)], check=True)
    data = binary.read_bytes()
    words = struct.unpack("<" + "I" * (len(data) // 4), data)
    lines.append(f"inline constexpr uint32_t {name}[] = {{")
    for i in range(0, len(words), 8):
        lines.append("    " + ", ".join(f"0x{word:08x}" for word in words[i:i + 8]) + ",")
    lines.append("};")
lines.append('inline constexpr char FrameGraphIndexedHLSL[] = R"hlsl(' + (source / "FrameGraphIndexed.hlsl").read_text(encoding="utf-8") + ')hlsl";')
lines.append("// clang-format on")
(source / "FrameGraphSPIRV.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
