def run_git_with_retry(label, operation):
    last_error = None

    for attempt, delay in enumerate([0, *GIT_RETRY_DELAYS], start=1):
        if delay > 0:
            print(f"[retry] {label} attempt {attempt}/{len(GIT_RETRY_DELAYS) + 1} after {delay}s")
            time.sleep(delay)

        try:
            return operation()
        except GitCommandError as error:
            last_error = error
            stderr = error.stderr.strip() if error.stderr else str(error)
            print(f"[git] {label} failed on attempt {attempt}/{len(GIT_RETRY_DELAYS) + 1}: {stderr}")

    if last_error is None:
        raise RuntimeError(f"{label} failed without a captured git error")

    raise last_error


def is_commit_hash(ref):
    return bool(ref) and COMMIT_HASH_RE.fullmatch(ref) is not None

def compute_package_key(package, platform=None):
    """Compute a hash from package config to detect changes."""
    relevant = {k: v for k, v in package.items() if k not in ('name',)}
    target = platform or args.platform
    if target in MACOS_ARCHITECTURES:
        relevant['macos_architecture'] = MACOS_ARCHITECTURES[target]
    elif target == 'IOS':
        relevant['ios_target'] = ios_build_identity()
    elif target == 'HarmonyOS':
        relevant['ohos_toolchain'] = harmonyos_toolchain_identity()
        patch = Path(args.engine) / 'cmake/patches' / f"{package['name']}.patch"
        if patch.is_file():
            relevant['ohos_patch'] = hashlib.sha256(patch.read_bytes()).hexdigest()
    content = json.dumps(relevant, sort_keys=True)
    return hashlib.sha256(content.encode()).hexdigest()[:16]

