def resolve_harmonyos_sdk():
    value = args.ohos_sdk or os.environ.get('OHOS_SDK_NATIVE')
    if not value:
        parser.error('HarmonyOS requires --ohos-sdk <native-sdk> or OHOS_SDK_NATIVE')
    native = Path(value).resolve()
    for relative in ('build/cmake/ohos.toolchain.cmake', 'oh-uni-package.json', 'sysroot/usr/include'):
        if not (native / relative).exists():
            parser.error(f'HarmonyOS native SDK is missing {relative}: {native}')
    return native


def harmonyos_toolchain_identity():
    native = resolve_harmonyos_sdk()
    identity = hashlib.sha256()
    for relative in ('build/cmake/ohos.toolchain.cmake', 'oh-uni-package.json'):
        identity.update((native / relative).read_bytes())
    return {'sdk': native.as_posix(), 'hash': identity.hexdigest(), 'abi': 'arm64-v8a', 'stl': 'c++_shared'}


def fill_harmonyos_config(options):
    native = resolve_harmonyos_sdk()
    options['CMAKE_TOOLCHAIN_FILE'] = (native / 'build/cmake/ohos.toolchain.cmake').as_posix()
    options['OHOS_ARCH'] = 'arm64-v8a'
    options['OHOS_STL'] = 'c++_shared'
    options['CMAKE_POSITION_INDEPENDENT_CODE'] = 'ON'
    ninja = native / 'build-tools/cmake/bin' / ('ninja.exe' if os.name == 'nt' else 'ninja')
    if ninja.is_file():
        options['CMAKE_MAKE_PROGRAM'] = ninja.as_posix()


def package_options(package, platform):
    options = dict(package.get('options', {}))
    if platform == 'HarmonyOS':
        options.update(package.get('options_Android', {}))
    options.update(package.get(f'options_{platform}', {}))
    return options


def fill_common_options(options, build_type, install_dir):
    cmake_modules_path = os.path.join(args.engine, 'cmake', 'thirdparty').replace('\\', '/')
    options['3RD_PATH'] = get_platform_output_root()
    options['3RD_FIND_PATH'] = cmake_modules_path
    options['BUILD_TESTING'] = 'OFF'
    options['CMAKE_INSTALL_PREFIX'] = install_dir
    options['CMAKE_BUILD_TYPE'] = build_type
    # Several pinned dependencies predate CMake 4's compatibility floor.
    options['CMAKE_POLICY_VERSION_MINIMUM'] = '3.5'

    if args.platform == 'Android':
        fill_android_config(options)
    elif args.platform == 'HarmonyOS':
        fill_harmonyos_config(options)
    elif args.platform == 'IOS':
        fill_ios_config(options)
    elif args.platform in MACOS_ARCHITECTURES:
        options.update(apple_target_options(args.platform))

def slang_build_identity(source_dir, options):
    try:
        revision = subprocess.check_output(["git", "-C", source_dir, "rev-parse", "HEAD"], text=True).strip()
    except subprocess.CalledProcessError:
        revision = ''
    payload = revision + '\n' + json.dumps(options, sort_keys=True)
    return hashlib.sha256(payload.encode()).hexdigest()


def build_package_type(name, source_dir, build_type, options, cache, components, header_only=False):
    option_error = apple_option_error(options, args.platform)
    if option_error:
        print(f'[apple] {option_error}')
        return False
    platform_build = args.platform
    if args.platform == 'HarmonyOS':
        platform_build += '_' + hashlib.sha256(json.dumps(harmonyos_toolchain_identity(), sort_keys=True).encode()).hexdigest()[:12]
    elif args.platform == 'IOS':
        platform_build += '_' + ios_build_identity()['platform']
    build_dir = os.path.join(source_dir, f"build_{platform_build}_{build_type}")
    install_dir = os.path.join(build_dir, 'install')

    fill_common_options(options, build_type, install_dir)

    # Reusing Slang's build tree across a tag/option change can keep generated
    # modules from the previous version; rebuild from scratch when it changes.
    identity = slang_build_identity(source_dir, options) if name == 'slang' else None
    identity_file = os.path.join(build_dir, 'sky_build_identity')
    if identity is not None and os.path.isdir(build_dir):
        cached_identity = ''
        if os.path.exists(identity_file):
            cached_identity = Path(identity_file).read_text(encoding='utf-8').strip()
        if cached_identity != identity:
            shutil.rmtree(build_dir)

    if header_only:
        # header-only: configure + install only, skip build
        Path(build_dir).mkdir(parents=True, exist_ok=True)

        cmake_cmd = ["cmake", "-S", source_dir, "-B", build_dir, "-G", tool_chain[args.platform]]
        if cache:
            cmake_cmd = ["cmake", "-S", source_dir, "-C", cache, "-B", build_dir, "-G", tool_chain[args.platform]]
        if options:
            for key, value in options.items():
                cmake_cmd.extend([f"-D{key}={value}"])

        cmake_cmd.extend(get_extra_cmake_args())

        print(f"  [configure] {source_dir}")
        run_stream(cmake_cmd)

        install_cmd = ["cmake", "--install", build_dir, "--config", build_type]
        print(f"  [install] {build_type}")
        run_stream(install_cmd)
    else:
        run_cmake(build_dir, source_dir, build_type, options, cache, components, log_name=name)

    if not header_only:
        artifact_error = apple_artifact_error(install_dir, args.platform)
        if artifact_error:
            print(f'[apple] {artifact_error}')
            return False
    copy_package(name, install_dir, build_type)
    if identity is not None:
        Path(identity_file).write_text(identity + '\n', encoding='utf-8')
    return True

def build_slang_host_generators(source_dir, options):
    # Cross builds run generators on the host, then pass their directory to
    # the target build via SLANG_GENERATORS_PATH.
    host_build = os.path.join(source_dir, 'build_host_generators')
    generator = tool_chain['Win32'] if os.name == 'nt' else 'Ninja'
    revision = subprocess.check_output(["git", "-C", source_dir, "rev-parse", "HEAD"], text=True).strip()
    version = options.get('SLANG_VERSION_NUMERIC', '')
    embed_core = options.get('SLANG_EMBED_CORE_MODULE', '')
    architecture = host_architecture()
    system = host_platform.system()
    host_options = {key: value for key, value in options.items()
                    if key.startswith('SLANG_') and key != 'SLANG_GENERATORS_PATH'}
    host_identity = json.dumps({'revision': revision, 'version': version, 'embed': embed_core,
                                'generator': generator, 'system': system, 'architecture': architecture,
                                'options': host_options}, sort_keys=True)
    revision_file = os.path.join(host_build, 'source-revision.txt')

    def find_generators_dir():
        # slang emits generators under generators/<config>/bin; locate by the
        # slang-bootstrap executable (the one the target build references).
        for root, _dirs, files in os.walk(host_build):
            if ('slang-bootstrap.exe' if os.name == 'nt' else 'slang-bootstrap') in files:
                return normalize_cmake_path(root)
        return None

    existing = find_generators_dir()
    cached_revision = ''
    if os.path.exists(revision_file):
        cached_revision = Path(revision_file).read_text(encoding='utf-8').strip()
    # Generators are version-coupled to the Slang sources; a tag bump must not
    # reuse the previous checkout's host tools.
    if existing and cached_revision == host_identity:
        artifact_error = host_generator_error(existing)
        if artifact_error is None:
            return existing
        print(f'[slang] cached host generators are invalid: {artifact_error}')
    if os.path.isdir(host_build):
        shutil.rmtree(host_build)

    print("  [slang] building host generators")
    cmake_cmd = ["cmake", "-S", source_dir, "-B", host_build, "-G", generator,
                 "-DCMAKE_BUILD_TYPE=Release", "-DCMAKE_POLICY_VERSION_MINIMUM=3.5"]
    if system == 'Darwin':
        cmake_cmd += [f'-DCMAKE_OSX_ARCHITECTURES={architecture}', '-DCMAKE_OSX_SYSROOT=macosx']
    for key, value in host_options.items():
        cmake_cmd.append(f"-D{key}={value}")
    run_stream(cmake_cmd)
    run_stream(["cmake", "--build", host_build, "--config", "Release", "--target", "all-generators",
                "--parallel", str(args.jobs or os.cpu_count() or 4)])
    generators = find_generators_dir()
    artifact_error = host_generator_error(generators)
    if artifact_error:
        print(f'[slang] {artifact_error}')
        return None
    Path(revision_file).write_text(host_identity + '\n', encoding='utf-8')
    return generators


def host_architecture():
    architecture = host_platform.machine().lower()
    return {'amd64': 'x86_64', 'aarch64': 'arm64'}.get(architecture, architecture)


def host_generator_error(directory):
    if directory is None:
        return 'Slang host generators missing after build'
    bootstrap = Path(directory) / ('slang-bootstrap.exe' if os.name == 'nt' else 'slang-bootstrap')
    if not bootstrap.is_file() or not os.access(bootstrap, os.X_OK):
        return f'Slang host bootstrap is not executable: {bootstrap}'
    if host_platform.system() == 'Darwin':
        with bootstrap.open('rb') as stream:
            if stream.read(4) not in MACHO_MAGICS:
                return f'Slang host bootstrap is not a native Mach-O executable: {bootstrap}'
        architecture = host_architecture()
        platform = next((name for name, target in MACOS_ARCHITECTURES.items() if target == architecture), None)
        if platform is None:
            return f'unsupported Slang host architecture: {architecture}'
        return apple_artifact_error(Path(directory).parent, platform)
    return None




def build_package(name, source_dir, options, cache, components, header_only=False):
    print("build package ...", name)
    if name == 'slang':
        # GitVersion caches SLANG_VERSION_* in CMakeCache.txt, so a reused build
        # directory would keep reporting the previous tag's version.
        try:
            described = subprocess.check_output(
                ["git", "-C", source_dir, "describe", "--tags", "--match", "v20[2-9][0-9].[0-9]*"],
                text=True, stderr=subprocess.DEVNULL).strip()
        except subprocess.CalledProcessError:
            described = ''
        match = re.match(r'^v(\d+(?:\.\d+)*)', described)
        if match:
            options['SLANG_VERSION_NUMERIC'] = match.group(1)
            options['SLANG_VERSION_FULL'] = described[1:]
    cross_macos = args.platform in MACOS_ARCHITECTURES and MACOS_ARCHITECTURES[args.platform] != host_architecture()
    if name == 'slang' and (args.platform in ('IOS', 'Android', 'HarmonyOS') or cross_macos):
        generators = build_slang_host_generators(source_dir, options)
        if not generators:
            return False
        options['SLANG_GENERATORS_PATH'] = generators
    if header_only:
        if not build_package_type(name, source_dir, 'Release', dict(options), cache, components, header_only=True):
            return False
    else:
        if not build_package_type(name, source_dir, 'Debug', dict(options), cache, components):
            return False
        if not build_package_type(name, source_dir, 'Release', dict(options), cache, components):
            return False
    print("build package done")
    return True

def process_package(package):
    name = package.get('name')
    url = package.get('url')
    tag = package.get('tag')
    commit = package.get('commit')
    custom = package.get('custom')
    custom_need_platform = package.get('custom_need_platform')
    cache = package.get('cache')
    platforms = package.get('platforms')
    submodule = package.get('submodule')
    submodules = package.get('submodules')
    components = package.get('components')
    source = package.get('source')
    is_tool = package.get('is_tool')
    options = package_options(package, args.platform)
    header_only = package.get('header_only', False)
    custom_engine = package.get('custom_engine', False)
    custom_only = package.get('custom_only', False)
    if len(name) == 0:
        return
    option_error = apple_option_error(options, args.platform)
    if option_error:
        print(f'[apple] {option_error}')
        return False

    print("build package ...", name)

    if platforms and args.platform not in platforms:
        return

    clone_dir = os.path.join(args.intermediate, name)
    need_full_history = submodule or submodules
    if commit and not is_commit_hash(commit):
        raise ValueError(f"Commit '{commit}' for package '{name}' is not a full 40-character git commit id")

    if not os.path.exists(clone_dir):
        clone_kwargs = {}
        if not need_full_history:
            clone_kwargs['depth'] = 1
            if tag:
                clone_kwargs['branch'] = tag
        repo = run_git_with_retry(f"clone {name}", lambda: Repo.clone_from(url, str(clone_dir), **clone_kwargs))
    else:
        repo = Repo(str(clone_dir))

    if cache:
        cache = os.path.join(str(clone_dir), cache)
        cache = str(os.path.normpath(cache))

    if args.clean:
        print(f"清理 '{name}'")
        repo.git.clean('-xdf')
        return

    if commit:
        run_git_with_retry(f"fetch commit for {name}", lambda: repo.git.fetch('--depth=1', 'origin', commit))
        repo.git.checkout('--detach', 'FETCH_HEAD')
    elif tag and need_full_history:
        run_git_with_retry(f"fetch tags for {name}", lambda: repo.git.fetch('--tags'))
        if tag not in repo.tags:
            raise ValueError(f"Tag '{tag}' 不存在于仓库中")

        branch_name = f"Branch_{tag}"

        if branch_name not in repo.branches:
            repo.git.checkout(tag, b=branch_name)
        else:
            repo.git.checkout(branch_name)
    elif tag:
        # existing shallow checkout: enforce the configured tag (only fresh
        # clones get branch=tag; without this a stale checkout survives a
        # tag bump in thirdparty.json)
        run_git_with_retry(f"fetch tag {tag} for {name}", lambda: repo.git.fetch('--depth=1', 'origin', f'refs/tags/{tag}'))
        repo.git.checkout('--detach', 'FETCH_HEAD')

    # use custom step
    if custom and custom_engine:
        custom = os.path.join(args.engine, custom)
    if custom:
        custom_cmd = [sys.executable, custom]
        if custom_need_platform is True:
            custom_cmd.extend(['-p', args.platform])
        if custom_engine:
            custom_cmd.extend(['-o', normalize_cmake_path(args.output)])
        if args.platform == 'HarmonyOS':
            os.environ['OHOS_SDK_NATIVE'] = str(resolve_harmonyos_sdk())
        subprocess.run(custom_cmd, cwd=str(clone_dir), check=True)

    # init submodule
    if submodule is True:
        print(repo.submodules)

        for sm in repo.submodules:
            sm.update(init=True, recursive=True, force=True)

    if submodules:
        for subName in submodules:
            update_cmd = ["git", "submodule", "update", "--init", "--recursive", subName]
            subprocess.run(update_cmd, cwd=clone_dir, check=True)

    # try to apply patch
    patch_path = os.path.join(args.engine, 'cmake', 'patches', name + '.patch')
    if os.path.exists(patch_path):
        repo.git.reset('--hard')
        repo.git.clean('-f')
        repo.git.apply(patch_path)
        print('Apply Patch 成功')

    if custom_only:
        return

    source_dir = clone_dir
    if source:
        source_dir = os.path.join(str(clone_dir), source)

    if is_tool is True:
        return

    return build_package(name, source_dir, options, cache, components, header_only=header_only)


def pack_output(zip_path):
    """Optional, explicit packaging.

    Zips the platform output to the given path. It is opt-in (--archive) and
    does not write anything into tracked configuration.
    """
    output_root = Path(get_platform_output_root())
    if not output_root.exists():
        print(f"[archive] output does not exist: {output_root}")
        return

    Path(zip_path).parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_DEFLATED) as zf:
        for file in sorted(output_root.rglob('*')):
            if file.is_file() and file.name != METADATA_FILE:
                zf.write(file, file.relative_to(output_root))

    size_mb = os.path.getsize(zip_path) / (1024 * 1024)
    print(f"[archive] {zip_path} ({size_mb:.1f} MB)")


def list_packages(packages):
    print(f"{'Name':<20} {'Tag':<25} {'Type':<12} {'Platforms'}")
    print("-" * 80)
    for pkg in packages:
        name = pkg.get('name', '')
        tag = pkg.get('tag', '(no tag)')
        ptype = 'header-only' if pkg.get('header_only') else 'tool' if pkg.get('is_tool') else 'static'
        platforms = ', '.join(pkg.get('platforms', ['all']))
        print(f"{name:<20} {tag:<25} {ptype:<12} {platforms}")

def check_platform(packages, platform):
    """Read-only validation of one platform: compare the pinned package
    definitions in thirdparty.json against the build_metadata.json written when
    the platform output was last built.

    Returns (hard_fail, warn): hard_fail counts packages that are missing or
    stale (pin changed since the output was built); warn counts packages whose
    metadata is current but whose output directory is gone.
    """
    output_root = os.path.join(args.output, platform)
    metadata_path = os.path.join(output_root, METADATA_FILE)

    print(f"\n[{platform}] {output_root}")
    if not os.path.exists(metadata_path):
        print(f"  no {METADATA_FILE} - third-party output not built for this platform")
        return 1, 0

    with open(metadata_path, 'r', encoding='utf-8') as f:
        metadata = json.load(f)

    print(f"{'package':<20} {'state':<8} detail")
    print('-' * 64)

    hard_fail = 0
    warn = 0
    for pkg in packages:
        name = pkg.get('name', '')
        if not name:
            continue

        platforms = pkg.get('platforms')
        if platforms and platform not in platforms:
            continue

        package_key = compute_package_key(pkg, platform)
        entry = metadata.get(name)
        out_dir = os.path.join(output_root, name)

        if entry is None:
            state = 'MISSING'
            detail = 'not built (absent from build_metadata)'
            hard_fail += 1
        elif entry.get('key') != package_key:
            state = 'STALE'
            detail = f"meta={entry.get('key')} pin={package_key}"
            hard_fail += 1
        else:
            output_error = package_output_error(pkg, platform)
            if output_error:
                state = 'INVALID' if pkg.get('is_tool') or os.path.isdir(out_dir) else 'NOOUT'
                detail = output_error
                if state == 'NOOUT':
                    warn += 1
                else:
                    hard_fail += 1
            else:
                state = 'ok'
                detail = pkg.get('tag') or pkg.get('commit', '')
                if len(detail) == 40:
                    detail = detail[:12]

        print(f"{name:<20} {state:<8} {detail}")

    print(f"  -> {hard_fail} missing/stale, {warn} output-missing")
    return hard_fail, warn


def app_main():
    json_file = os.path.join(args.engine, 'cmake', 'thirdparty.json')
    with open(json_file, 'r', encoding='utf-8') as file:
        data = json.load(file)

    packages = data.get('packages', [])

    if args.list:
        list_packages(packages)
        return

    if args.check:
        if not args.output:
            parser.error('--output is required for --check: specify the third-party output directory')
        if args.platform:
            platforms = [args.platform]
        else:
            platforms = [
                name for name in sorted(os.listdir(args.output))
                if os.path.isfile(os.path.join(args.output, name, METADATA_FILE))
            ]
        if not platforms:
            print(f"[check] no platform build_metadata.json found under {args.output}")
            sys.exit(1)

        total_hard = 0
        total_warn = 0
        for platform in platforms:
            hard_fail, warn = check_platform(packages, platform)
            total_hard += hard_fail
            total_warn += warn

        if total_hard != 0:
            print(f"\n[check] FAIL: {total_hard} package(s) missing/stale")
            sys.exit(1)
        if total_warn != 0 and args.strict:
            print(f"\n[check] FAIL (strict): {total_warn} package(s) with missing output")
            sys.exit(1)
        print("\n[check] OK")
        return

    if not args.output:
        parser.error('--output is required: specify the third-party output directory')
    if args.platform == 'HarmonyOS':
        resolve_harmonyos_sdk()
    ensure_default_intermediate()

    metadata = load_build_metadata()

    if args.target:
        filtered = list(filter(lambda pkg: pkg['name'] == args.target, packages))
    else:
        filtered = packages

    built_any = False
    for package in filtered:
        name = package.get('name', '')
        if not name:
            continue
        platforms = package.get('platforms')
        if platforms and args.platform not in platforms:
            continue
        package_key = compute_package_key(package)

        if not args.force and not args.clean and is_package_up_to_date(metadata, name, package_key):
            output_error = package_output_error(package, args.platform)
            if not output_error:
                print(f"[skip] {name} (已是最新, 使用 -f 强制重建)")
                continue
            print(f'[rebuild] {name}: {output_error}')

        if process_package(package) is False:
            sys.exit(1)

        if not args.clean:
            output_error = package_output_error(package, args.platform)
            if output_error:
                print(f'[third-party] {output_error}')
                sys.exit(1)
            mark_package_built(metadata, name, package_key)
            save_build_metadata(metadata)
            write_cmake_cache()
            built_any = True

    # Optional, explicit packaging (never run by default, never mutates tracked files).
    if args.archive and not args.clean:
        pack_output(args.archive)

if __name__ == "__main__":
    app_main()
