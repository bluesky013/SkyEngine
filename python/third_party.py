def apple_target_options(platform):
    if platform in MACOS_ARCHITECTURES:
        return {'CMAKE_OSX_ARCHITECTURES': MACOS_ARCHITECTURES[platform], 'CMAKE_OSX_SYSROOT': 'macosx'}
    if platform == 'IOS':
        target = ios_build_identity()
        return {'PLATFORM': target['platform'], 'CMAKE_OSX_ARCHITECTURES': target['architecture'],
                'CMAKE_OSX_SYSROOT': target['sdk']}
    return {}


def apple_option_error(options, platform):
    expected = apple_target_options(platform)
    overrides = dict(options)
    extra = get_extra_cmake_args()
    for index, option in enumerate(extra):
        value = extra[index + 1] if option == '-D' and index + 1 < len(extra) else option[2:] if option.startswith('-D') else ''
        key, separator, value = value.partition('=')
        if separator:
            overrides[key.split(':', 1)[0]] = value
    for key, value in expected.items():
        if key not in overrides:
            continue
        configured = str(overrides[key])
        if key == 'CMAKE_OSX_SYSROOT':
            configured = Path(configured).name.lower()
            matches = configured == value or (configured.startswith(value) and configured.endswith('.sdk'))
        else:
            matches = configured == value
        if not matches:
            return f'{platform} requires {key}={value}, received {overrides[key]}'
    return None


def apple_runtime_binaries(package_root):
    root = Path(package_root).resolve()
    pending = [root / name for name in ('lib', 'bin') if (root / name).exists() or (root / name).is_symlink()]
    directories = set()
    binaries = set()
    while pending:
        path = pending.pop()
        actual = Path(os.path.realpath(path))
        if not actual.is_relative_to(root):
            return [], f'runtime symlink escapes package: {path}'
        if not actual.exists():
            return [], f'broken runtime symlink: {path}'
        if actual.is_dir():
            if actual not in directories:
                directories.add(actual)
                pending.extend(actual.iterdir())
            continue
        if actual.is_file():
            with actual.open('rb') as stream:
                magic = stream.read(4)
            if actual.suffix in ('.a', '.dylib') or '.so' in actual.suffixes or magic in MACHO_MAGICS:
                binaries.add(actual)
    return sorted(binaries), None


def apple_artifact_error(package_root, platform):
    target = apple_target_options(platform)
    if not target:
        return None
    architecture = target['CMAKE_OSX_ARCHITECTURES']
    sdk = target['CMAKE_OSX_SYSROOT']
    binaries, discovery_error = apple_runtime_binaries(package_root)
    if discovery_error:
        return discovery_error
    if not binaries:
        return f'no native artifacts found in {package_root}'
    lipo = shutil.which('lipo')
    otool = shutil.which('otool')
    if not lipo or not otool:
        return 'Apple artifact verification requires lipo and otool from Xcode Command Line Tools'
    expected_platform = {'macosx': 1, 'iphoneos': 2, 'iphonesimulator': 7}[sdk]
    for binary in binaries:
        result = subprocess.run([lipo, '-archs', str(binary)], capture_output=True, text=True)
        if result.returncode:
            return f'cannot inspect architecture of {binary}: {result.stderr.strip()}'
        architectures = set(result.stdout.split())
        if architectures != {architecture}:
            return f'{binary} has architectures {sorted(architectures)}, expected only {architecture}'
        result = subprocess.run([otool, '-l', str(binary)], capture_output=True, text=True)
        if result.returncode:
            return f'cannot inspect SDK platform of {binary}: {result.stderr.strip()}'
        platforms = {int(value) for value in re.findall(r'^\s*platform\s+(\d+)\s*$', result.stdout, re.MULTILINE)}
        if 'LC_VERSION_MIN_MACOSX' in result.stdout:
            platforms.add(1)
        if 'LC_VERSION_MIN_IPHONEOS' in result.stdout:
            platforms.add(7 if architecture == 'x86_64' else 2)
        if platforms != {expected_platform}:
            return f'{binary} has SDK platforms {sorted(platforms)}, expected {sdk}'
    return None


def tool_source_error(package):
    source = Path(args.intermediate or os.path.join(args.output, 'intermediate')) / package['name']
    if not source.is_dir():
        return f'tool source missing: {source}'
    required = ('ios.toolchain.cmake',) if package['name'] == 'ios-cmake' else ()
    for relative in required:
        if not (source / relative).is_file():
            return f'tool file missing: {source / relative}'
    reference = package.get('commit') or package.get('tag')
    if not reference:
        return f'tool has no pinned source reference: {package["name"]}'
    head = subprocess.run(['git', '-C', str(source), 'rev-parse', 'HEAD'], capture_output=True, text=True)
    pinned = subprocess.run(['git', '-C', str(source), 'rev-parse', '--verify', reference + '^{commit}'],
                            capture_output=True, text=True)
    if head.returncode or pinned.returncode or head.stdout.strip() != pinned.stdout.strip():
        return f'tool checkout does not match pinned reference {reference}: {source}'
    if required:
        changed = subprocess.run(['git', '-C', str(source), 'diff', '--quiet', 'HEAD', '--', *required])
        if changed.returncode:
            return f'tool files differ from pinned checkout: {source}'
    return None


def package_output_error(package, platform):
    if package.get('is_tool'):
        return tool_source_error(package)
    output = Path(args.output) / platform / package['name']
    if not output.is_dir():
        return f'package output missing: {output}'
    if not package.get('header_only'):
        return apple_artifact_error(output, platform)
    return None


def run_stream(cmd, log_file=None):
    """Run a command, streaming merged stdout/stderr to the console and optionally a log file."""
    process = subprocess.Popen(
        cmd,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding='utf-8',
        errors='replace',
        bufsize=1,
    )
    if process.stdout is not None:
        for line in process.stdout:
            _write_stdout(line)
            if log_file:
                log_file.write(line)
                log_file.flush()
    process.wait()
    if process.returncode != 0:
        raise subprocess.CalledProcessError(process.returncode, cmd)

def install_slang_static_libs(build_dir, build_type, platform):
    # Copy static archives into install/lib so copy_package publishes
    # lib/<Config>/{*.a,*.lib}; both Xcode and Ninja use a config subdirectory.
    ext = '.lib' if platform == 'Win32' else '.a'
    src = os.path.join(build_dir, build_type, 'lib')
    if not os.path.isdir(src):
        src = os.path.join(build_dir, 'lib')
    dst = os.path.join(build_dir, 'install', 'lib')
    if not os.path.isdir(src):
        return
    os.makedirs(dst, exist_ok=True)

    def is_stale_compiler_library(entry):
        # A static rebuild can sit next to shared libraries from an older package
        # in a reused build directory. Do not publish those.
        for suffix in ('.dylib', '.so', '.dll'):
            if entry.endswith(suffix):
                stem = entry[:-len(suffix)]
                return stem in ('libslang', 'slang', 'libslang-compiler', 'slang-compiler') or stem.startswith('libslang-compiler.')
        return False

    for directory in {src, dst}:
        for entry in os.listdir(directory):
            if is_stale_compiler_library(entry):
                os.remove(os.path.join(directory, entry))

    for entry in os.listdir(src):
        if entry.endswith(ext):
            shutil.copy2(os.path.join(src, entry), os.path.join(dst, entry))
            print(f"  [slang-static] installed {entry}")
    # Slang's static archives reference bundled third-party archives (lz4 /
    # miniz / cmark), which live under external/*/ build dirs, not lib/.
    for root, _dirs, files in os.walk(build_dir):
        for entry in files:
            if entry.endswith(ext) and (entry.startswith('lz4') or entry.startswith('liblz4') or
                                        entry.startswith('miniz') or entry.startswith('libminiz') or
                                        entry.startswith('cmark') or entry.startswith('libcmark')):
                target = os.path.join(dst, entry)
                if not os.path.exists(target):
                    shutil.copy2(os.path.join(root, entry), target)
                    print(f"  [slang-static] installed {entry}")


def run_cmake(build_dir: str, source_dir: str, build_type, options: dict[str, str] | None = None, cache: str | None = None,
              components: list[str] | None = None, log_name: str | None = None):
    # 确保构建目录存在
    Path(build_dir).mkdir(parents=True, exist_ok=True)

    # 准备CMake命令
    if cache:
        cmake_cmd = ["cmake", "-S", source_dir, "-C", cache, "-B", build_dir, "-G", tool_chain[args.platform]]
    else:
        cmake_cmd = ["cmake", "-S", source_dir, "-B", build_dir, "-G", tool_chain[args.platform]]

    # 添加选项
    if options:
        for key, value in options.items():
            cmake_cmd.extend([f"-D{key}={value}"])

    cmake_cmd.extend(get_extra_cmake_args())

    log_file = None
    if log_name:
        log_path = os.path.join(get_log_dir(), f"{log_name}_{build_type}.log")
        log_file = open(log_path, 'w', encoding='utf-8')

    try:
        # 执行CMake配置
        print(f"  [configure] {source_dir}")
        if log_file:
            log_file.write(f"=== configure ===\n")
        run_stream(cmake_cmd, log_file)

        # 执行 Build
        build_cmd = ["cmake", "--build", build_dir, "--config", build_type]
        if args.jobs > 0:
            build_cmd.extend(["--parallel", str(args.jobs)])
        else:
            build_cmd.append("--parallel")
        print(f"  [build] {build_type}")
        if log_file:
            log_file.write(f"=== build ===\n")
        run_stream(build_cmd, log_file)

        # 执行 Install
        install_cmd = ["cmake", "--install", build_dir, "--config", build_type]

        if components:
            for component in components:
                install_cmd.extend(["--component", component])

        # A reused build tree keeps old runtime libraries in install/lib; a
        # static package must not publish them.
        if log_name == 'slang' and str(options.get('SLANG_LIB_TYPE', '')).upper() == 'STATIC':
            shutil.rmtree(os.path.join(build_dir, 'install', 'lib'), ignore_errors=True)

        print(f"  [install] {build_type}")
        if log_file:
            log_file.write(f"=== install ===\n")
        run_stream(install_cmd, log_file)

        if log_name == 'slang' and str(options.get('SLANG_LIB_TYPE', '')).upper() == 'STATIC':
            install_slang_static_libs(build_dir, build_type, args.platform)

        print(f"  [done] {build_type} 成功")
    except subprocess.CalledProcessError as e:
        if log_file:
            log_file.write(f"=== ERROR ===\n")
        print(f"CMake执行失败 (exit {e.returncode})")
        raise
    finally:
        if log_file:
            log_file.close()

def copy_package(name, install_dir, build_type):
    src_inc_path = os.path.join(install_dir, "include")
    src_src_path = os.path.join(install_dir, "src")
    src_lib_path = os.path.join(install_dir, "lib")
    src_bin_path = os.path.join(install_dir, "bin")

    platform_output_root = get_platform_output_root()

    dst_inc_path = os.path.join(platform_output_root, name, "include")
    dst_src_path = os.path.join(platform_output_root, name, "src")
    dst_lib_path = os.path.join(platform_output_root, name, "lib", build_type)
    dst_bin_path = os.path.join(platform_output_root, name, "bin")

    src_inc = Path(str(src_inc_path))
    src_src = Path(str(src_src_path))
    src_lib = Path(str(src_lib_path))
    src_bin = Path(str(src_bin_path))

    dst_inc = Path(str(dst_inc_path))
    dst_src = Path(str(dst_src_path))
    dst_lib = Path(str(dst_lib_path))
    dst_bin = Path(str(dst_bin_path))

    for src, dst in [(src_inc, dst_inc), (src_src, dst_src), (src_bin, dst_bin), (src_lib, dst_lib)]:
        if src.exists():
            if dst.exists():
                shutil.rmtree(dst)
            shutil.copytree(src, dst, symlinks=True)


def get_android_sdk_path():
    possible_names = ['ANDROID_HOME', 'ANDROID_SDK_ROOT', 'ANDROID_SDK']

    for name in possible_names:
        value = os.environ.get(name)
        if not value:
            continue
        path = os.path.normpath(value)
        if os.path.exists(path):
            print(f"find Android SDK: {path} from {name}")
            return path
    raise Exception("Android SDK path not found.")

