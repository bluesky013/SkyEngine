def write_cmake_cache():
    # Per-platform cache so switching platforms (iOS/Android/macOS) never
    # clobbers another platform's 3RD_PATH. cmake/options.cmake loads the one
    # matching the current build platform.
    cache_path = os.path.join(args.output, f'thirdparty_cache_{args.platform}.cmake')
    output_root = normalize_cmake_path(args.output)
    platform_output_path = normalize_cmake_path(get_platform_output_root())
    engine_path = normalize_cmake_path(args.engine)

    Path(args.output).mkdir(parents=True, exist_ok=True)
    with open(cache_path, 'w', encoding='utf-8') as f:
        f.write('# Auto-generated by python/third_party.py\n')
        f.write('# Do not edit manually.\n')
        f.write(f'set(SKY_THIRD_PARTY_PLATFORM "{args.platform}" CACHE STRING "SkyEngine third-party platform" FORCE)\n')
        f.write(f'set(SKY_THIRD_PARTY_ENGINE_ROOT "{engine_path}" CACHE PATH "SkyEngine root" FORCE)\n')
        f.write(f'set(SKY_THIRD_PARTY_OUTPUT_ROOT "{output_root}" CACHE PATH "SkyEngine third-party output root" FORCE)\n')
        f.write(f'set(SKY_THIRD_PARTY_{args.platform}_PATH "{platform_output_path}" CACHE PATH "SkyEngine third-party path for {args.platform}" FORCE)\n')
        f.write(f'set(3RD_PATH "{platform_output_path}" CACHE PATH "SkyEngine 3rd path" FORCE)\n')


